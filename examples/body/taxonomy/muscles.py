# 別名比對用：長的別名先比，避免「斜方肌」搶先吃掉「上斜方肌」
_LOOKUP = sorted(
    [(alias, canon) for canon, aliases in SYNONYMS.items() for alias in [canon, *aliases]],
    key=lambda p: -len(p[0]),
)

# 這些是部位或功能描述，不是肌肉，不納入肌群索引
NOT_A_MUSCLE = re.compile(
    r"活動度|關節|囊|韌帶|神經|曲度|姿勢|呼吸|穩定|控制|本體感覺|平衡|對位|"
    r"整體|全身|核心$|足弓|脊椎|胸廓|肋廓|骨盆$|肩胛骨$|髖$|膝$|踝$"
)


# 「中/下斜方肌」直接用 / 拆會得到沒有意義的「中」，先展開成完整名稱
_PRE = [
    (re.compile(r"(上|中|下)\s*[/／]\s*(上|中|下)\s*斜方肌"), r"\1斜方肌、\2斜方肌"),
    (re.compile(r"腹?內\s*[/／]\s*外\s*斜肌"), "腹內斜肌、腹外斜肌"),
    (re.compile(r"(臀大|臀中|臀小)\s*[/／]\s*(臀大|臀中|臀小)肌"), r"\1肌、\2肌"),
]


def split_targets(text: str | None) -> list[str]:
    """把 '上斜方肌、提肩胛肌' 這種字串拆成片段。"""
    if not text:
        return []
    for pattern, repl in _PRE:
        text = pattern.sub(repl, text)
    parts = re.split(r"[、,，/／;；]|\s+與\s+|\s+及\s+", text)
    return [p.strip(" 　()（）") for p in parts if p.strip(" 　()（）")]


def canonical(term: str) -> str | None:
    """把一個片段映射到標準肌群名；不是肌肉則回 None。"""
    term = term.strip()
    if not term or NOT_A_MUSCLE.search(term):
        return None
    for alias, canon in _LOOKUP:
        if alias and alias in term:
            return canon
    return None


def extract(*texts: str | None) -> list[str]:
    """從任意數量的描述字串中抽出去重後的標準肌群名（保持出現順序）。"""
    out: list[str] = []
    for text in texts:
        for part in split_targets(text):
            c = canonical(part)
            if c and c not in out:
                out.append(c)
    return out
